function initialLanguage() {
  try {
    const chosen = new URLSearchParams(location.search).get('lang') || localStorage.getItem('haze-language');
    if (chosen) return chosen;
  } catch {}
  return /^zh/i.test(navigator.language || 'zh') ? 'zh' : 'en';
}
let language = initialLanguage() === 'en' ? 'en' : 'zh';

export const getLanguage = () => language;
export const locale = () => (language === 'en' ? 'en-SG' : 'zh-CN');
export function t(key, vars = {}) {
  const text = strings[language][key] ?? strings.zh[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}
export function setLanguage(next) {
  language = next === 'en' ? 'en' : 'zh';
  // Remembered per browser; keep the address short (a ?lang= link still works for sharing).
  try {
    localStorage.setItem('haze-language', language);
    const url = new URL(location.href);
    if (url.searchParams.has('lang')) { url.searchParams.delete('lang'); history.replaceState(null, '', url); }
  } catch {}
}
export function localize(root = document) {
  document.documentElement.lang = language === 'en' ? 'en-SG' : 'zh-CN';
  document.title = t('title');
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr, t(key));
    }
  }
  for (const button of document.querySelectorAll('[data-language]')) {
    const on = button.dataset.language === language;
    button.classList.toggle('selected', on);
    button.setAttribute('aria-pressed', on);
  }
}
